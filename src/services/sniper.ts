/**
 * Permitted discrete trading volumes allocated to the bot:
 * $10, $15, $20, $30, $40, $45, or $50 USD
 */
export const VALID_TRADE_SIZES_USD = [10, 15, 20, 30, 40, 45, 50] as const;
export type ValidTradeSizeUsd = (typeof VALID_TRADE_SIZES_USD)[number];
export const DEFAULT_TRADE_SIZE_USD: ValidTradeSizeUsd = 10;

/**
 * Transparent Fee Structure:
 * 1. A 1% fee is applied to every trade executed by the bot.
 * 2. A 15% fee is applied to the profit generated by any trade exited in a profitable state (including manual exit / "exit all").
 * 3. Zero additional percentage fee on losing trades (only the initial 1% entry fee).
 */
export const BOT_ENTRY_FEE_PCT = 1.0;
export const BOT_ENTRY_FEE_RATE = 0.01;
export const BOT_PROFIT_FEE_PCT = 15.0;
export const BOT_PROFIT_FEE_RATE = 0.15;

export function isValidTradeSizeUsd(amount: number): amount is ValidTradeSizeUsd {
  return VALID_TRADE_SIZES_USD.includes(amount as ValidTradeSizeUsd);
}

export function sanitizeTradeSizeUsd(amount?: number | null): ValidTradeSizeUsd {
  if (typeof amount === 'number' && isValidTradeSizeUsd(amount)) {
    return amount;
  }
  return DEFAULT_TRADE_SIZE_USD;
}

