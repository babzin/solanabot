export async function exitAllSnipedPositions(): Promise<{
  count: number;
  totalSol: number;
  totalGrossSol: number;
  totalProfitFeeSol: number;
  profitableCount: number;
  losingCount: number;
  results: SnipeResult[];
}> {
  const active = getActivePositions();
  const results: SnipeResult[] = [];
  let totalSol = 0;
  let totalGrossSol = 0;
  let totalProfitFeeSol = 0;
  let profitableCount = 0;
  let losingCount = 0;

  for (const pos of active) {
    const res = await executeSnipeSell(pos.tokenMint, pos.tokenSymbol, pos.currentPriceUsd, 100);
    pos.status = 'CLOSED';
    pos.closedAt = Date.now();
    pos.remainingTokens = 0;
    pos.exitReason = 'MANUAL_EXIT_ALL';
    if (res.solAmount !== undefined) {
      totalSol += res.solAmount;
      totalGrossSol += (res.grossSol ?? res.solAmount);
      totalProfitFeeSol += (res.profitFeeSol ?? 0);
      if (res.isProfitable) {
        profitableCount++;
      } else {
        losingCount++;
      }
      pos.realizedSolProfit += (res.grossProfitSol ? (res.grossProfitSol - (res.profitFeeSol || 0)) : (res.solAmount - pos.solInvested));
    }
    results.push(res);
  }

  return {
    count: active.length,
    totalSol: Number(totalSol.toFixed(4)),
    totalGrossSol: Number(totalGrossSol.toFixed(4)),
    totalProfitFeeSol: Number(totalProfitFeeSol.toFixed(4)),
    profitableCount,
    losingCount,
    results,
  };
}

export async function checkActivePositionsTpSl(
  tokenMint: string,
  currentPriceUsd: number
): Promise<TpSlActionTriggered | null> {
  const notifications = await checkAllUserPositionsTpSl(tokenMint, currentPriceUsd);
  if (notifications.length > 0) {
    return notifications[0].action;
  }
  return null;
}
