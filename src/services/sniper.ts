/**
 * Executes a sell / exit trade for a specific user
 * Enforces the fee structure:
 * - 15% profit fee on any trade exited in a profitable state (whether manual or automated)
 * - 0% additional percentage-based fee on losing trades
 */
export async function executeUserSnipeSell(
  userId: string,
  tokenMint: string,
  tokenSymbol?: string,
  priceUsd?: number,
  sellPercent: number = 100
): Promise<SnipeResult> {
  const userPref = await getUserPreferences(userId);
  let keypair: Keypair | null = null;
  if (userPref.encryptedSecret && userPref.encryptionIv && userPref.encryptionTag) {
    try {
      keypair = decryptUserKeypair(userPref.encryptedSecret, userPref.encryptionIv, userPref.encryptionTag);
    } catch {}
  }
  if (!keypair) keypair = getServerKeypair();

  console.log(`🎯 [SNIPER ENGINE] Executing automated SELL (${sellPercent}%) for User ${userId} on ${tokenMint}...`);

  let solPrice = 155.0;
  try {
    const { fetchLiveSolPrice } = await import('./paperTrading.js');
    const p = await fetchLiveSolPrice();
    if (p > 10) solPrice = p;
  } catch {}

  const userPositions = inMemoryUserPositions.get(userId) || [];
  const pos = userPositions.find((p) => p.tokenMint === tokenMint && p.status !== 'CLOSED');

  try {
    if (keypair && env.HELIUS_RPC_URL) {
      try {
        const balRes = await axios.post(env.HELIUS_RPC_URL, {
          jsonrpc: '2.0',
          id: 'get-token-accounts',
          method: 'getTokenAccountsByOwner',
          params: [keypair.publicKey.toBase58(), { mint: tokenMint }, { encoding: 'jsonParsed' }],
        });

        const accounts = balRes.data?.result?.value || [];
        const fullTokenAmountRaw = accounts[0]?.account?.data?.parsed?.info?.tokenAmount?.amount;

        if (fullTokenAmountRaw && Number(fullTokenAmountRaw) > 0) {
          const tokenAmountRaw = Math.floor(Number(fullTokenAmountRaw) * (sellPercent / 100));
          const quoteUrl = `https://quote-api.jup.ag/v6/quote?inputMint=${tokenMint}&outputMint=${WSOL_MINT}&amount=${tokenAmountRaw}&slippageBps=2000`;
          const quoteRes = await axios.get(quoteUrl, { timeout: 3500 });
          const quoteData = quoteRes.data;

          const swapRes = await axios.post(
            'https://quote-api.jup.ag/v6/swap',
            {
              quoteResponse: quoteData,
              userPublicKey: keypair.publicKey.toBase58(),
              wrapAndUnwrapSol: true,
              dynamicComputeUnitLimit: true,
              prioritizationFeeLamports: userPref.priorityFeeLamports || 100_000,
            },
            { timeout: 4000 }
          );

          const { swapTransaction } = swapRes.data;
          const transaction = VersionedTransaction.deserialize(Buffer.from(swapTransaction, 'base64'));
          transaction.sign([keypair]);

          const txRes = await axios.post(env.HELIUS_RPC_URL, {
            jsonrpc: '2.0',
            id: 'sell-tx',
            method: 'sendTransaction',
            params: [
              Buffer.from(transaction.serialize()).toString('base64'),
              { skipPreflight: true, maxRetries: 2, encoding: 'base64' },
            ],
          });

          const signature = txRes.data?.result || `live_sell_${Date.now()}`;
          const grossSolReceived = Number(quoteData.outAmount || 0) / 1e9;

          // Fee Structure evaluation:
          const costBasisSol = pos ? pos.solInvested * (sellPercent / 100) : 0.1 * (sellPercent / 100);
          const grossProfitSol = grossSolReceived - costBasisSol;
          const isProfitable = grossProfitSol > 0.000001;

          let profitFeeSol = 0;
          let profitFeeUsd = 0;
          let netSolReceived = grossSolReceived;

          if (isProfitable) {
            // 15% fee on profit
            profitFeeSol = Number((grossProfitSol * BOT_PROFIT_FEE_RATE).toFixed(6));
            profitFeeUsd = Number((profitFeeSol * solPrice).toFixed(2));
            netSolReceived = Number((grossSolReceived - profitFeeSol).toFixed(6));
          }

          if (pos) {
            pos.profitFeeSol = (pos.profitFeeSol || 0) + profitFeeSol;
            pos.profitFeeUsd = (pos.profitFeeUsd || 0) + profitFeeUsd;
            pos.totalBotFeesSol = (pos.entryFeeSol || 0) + pos.profitFeeSol;
            pos.totalBotFeesUsd = (pos.entryFeeUsd || 0) + pos.profitFeeUsd;
          }

          // Route 15% profit fee on-chain to admin fee wallet
          if (isProfitable && profitFeeSol > 0.00005) {
            try {
              const { getAdminFeeWallet, dispatchFeeTransferOnChain, recordFeeRevenue } = await import('./adminConfig.js');
              const adminWallet = getAdminFeeWallet();
              let feeSig: string | undefined = undefined;
              if (adminWallet && keypair) {
                const feeRes = await dispatchFeeTransferOnChain(keypair, profitFeeSol, 'PROFIT_FEE_15PCT', { userId, tokenMint });
                if (feeRes.success) feeSig = feeRes.signature;
              }
              await recordFeeRevenue({
                feeType: 'PROFIT_FEE_15PCT',
                solAmount: profitFeeSol,
                usdAmount: profitFeeUsd,
                isLive: true,
                userId,
                tokenMint,
                signature: feeSig || signature,
              });
            } catch (feeErr: any) {
              console.warn('⚠️ Admin profit fee routing notice:', feeErr.message);
            }
          }

          console.log(
            `🚀 [SNIPER LIVE SELL] User ${userId} sold ${sellPercent}% of ${tokenSymbol || 'TOKEN'}. Gross: ${grossSolReceived.toFixed(4)} SOL | Profit: ${isProfitable ? '+' : ''}${grossProfitSol.toFixed(4)} SOL | 15% Fee: ${profitFeeSol.toFixed(4)} SOL | Net: ${netSolReceived.toFixed(4)} SOL. Tx: https://solscan.io/tx/${signature}`
          );

          return {
            success: true,
            simulated: false,
            signature,
            solAmount: netSolReceived,
            grossSol: grossSolReceived,
            grossProfitSol: Number(grossProfitSol.toFixed(6)),
            profitFeeSol,
            profitFeeUsd,
            isProfitable,
            tokenAmount: Number(tokenAmountRaw) / 1e6,
            tokenMint,
            tokenSymbol,
            priceUsd,
            routePlan: quoteData.routePlan?.[0]?.swapInfo?.label || 'Jupiter Sell Route',
          };
        }
      } catch (liveSellErr: any) {
        console.warn('⚠️ Live sell attempt fell back to simulation:', liveSellErr.message);
      }
    }

    // Simulation fallback
    const simulatedSignature = `sim_sell_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}`;

    const estimatedGrossSol = pos
      ? pos.solInvested * (sellPercent / 100) * ((priceUsd || pos.entryPriceUsd) / pos.entryPriceUsd)
      : 0.1 * (sellPercent / 100);

    const costBasisSol = pos ? pos.solInvested * (sellPercent / 100) : 0.1 * (sellPercent / 100);
    const grossProfitSol = estimatedGrossSol - costBasisSol;
    const isProfitable = grossProfitSol > 0.000001;

    let profitFeeSol = 0;
    let profitFeeUsd = 0;
    let netSolReceived = estimatedGrossSol;

    if (isProfitable) {
      profitFeeSol = Number((grossProfitSol * BOT_PROFIT_FEE_RATE).toFixed(6));
      profitFeeUsd = Number((profitFeeSol * solPrice).toFixed(2));
      netSolReceived = Number((estimatedGrossSol - profitFeeSol).toFixed(6));
    }

    if (pos) {
      pos.profitFeeSol = (pos.profitFeeSol || 0) + profitFeeSol;
      pos.profitFeeUsd = (pos.profitFeeUsd || 0) + profitFeeUsd;
      pos.totalBotFeesSol = (pos.entryFeeSol || 0) + pos.profitFeeSol;
      pos.totalBotFeesUsd = (pos.entryFeeUsd || 0) + pos.profitFeeUsd;
    }

    if (isProfitable && profitFeeSol > 0) {
      try {
        const { recordFeeRevenue } = await import('./adminConfig.js');
        await recordFeeRevenue({
          feeType: 'PROFIT_FEE_15PCT',
          solAmount: profitFeeSol,
          usdAmount: profitFeeUsd,
          isLive: false,
          userId,
          tokenMint,
          signature: simulatedSignature,
        });
      } catch {}
    }

    return {
      success: true,
      simulated: true,
      signature: simulatedSignature,
      solAmount: Number(netSolReceived.toFixed(4)),
      grossSol: Number(estimatedGrossSol.toFixed(4)),
      grossProfitSol: Number(grossProfitSol.toFixed(6)),
      profitFeeSol,
      profitFeeUsd,
      isProfitable,
      tokenAmount: pos ? pos.remainingTokens * (sellPercent / 100) : 100_000,
      tokenMint,
      tokenSymbol,
      priceUsd,
      routePlan: 'Jupiter Route Simulation',
    };
  } catch (err: any) {
    return {
      success: false,
      simulated: true,
      signature: `err_${Date.now()}`,
      solAmount: 0,
      tokenAmount: 0,
      tokenMint,
      tokenSymbol,
      error: err.message,
    };
  }
}

